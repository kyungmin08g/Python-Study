# [ 다형성(Polymorphism) ]
# 다형성(多形性)은 말 그대로 하나의 형태로 여러 종류의 객체를 다룰 수 있는 것을 의미합니다.
# 즉, 같은 메서드 호출을 했는데, 실제 객체의 종류에 따라 서로 다른 동작을 수행하는 것
# 호출하는 방법은 같지만 실제 객체가 무엇이냐에 따라 결과가 달라집니다.
# 
# 또한, 다형성이 중요한 이유는 부모 타입 하나로 여러 자식 객체를 처리할 수 있기 때문입니다. (객체가 실제로 어떤 클래스인지 신경 쓰지 않고 같은 메서드를 호출할 수 있다는 점이죠.)

# 상위 클래스 - Animal
class Animal:
    def sound(self):
        print("동물 소리")

# 하위 클래스 - Dog, Cat
# Dog와 Cat이 부모(상위) 클래스인 Animal의 sound()를 오버라이딩했습니다.
class Dog(Animal):
    def sound(self):
        print("멍멍")

class Cat(Animal):
    def sound(self):
        print("야옹")

# 각 객체 만들기
dog = Dog()
cat = Cat()

# 각 객체의 sound() 호출
dog.sound() # 멍멍
cat.sound() # 야옹

# [ 덕 타이핑(Duck Typing) ]
# Python은 덕 타이핑(Duck Typing)을 적극적으로 사용합니다.
# 덕 타이핑이란, 상속 관계가 없어도 객체의 실제 타입(클래스)보다, 그 객체가 어떤 행동을 할 수 있는지를 중요하게 보는 방식을 말합니다.
# 완벽한 비유를 한 말이 있습니다. -> "오리처럼 걷고, 오리처럼 꽥꽥거리면, 그건 오리로 취급한다." ('정확히 무슨 클래스?'보다 '필요한 기능을 가지고 있나?'를 확인합니다.)
# Dog인지 Cat인지 신경 쓰지 않고, 단순히 'sound() 메소드를 호출할 수 있냐?' 이것만 봅니다.
# 
# { 덕 타이핑(Duck Typing)의 장단점 }
# 장점으로는 코드가 굉장히 유연해집니다.
# 단점으로는 유연한 대신 실행하기 전까지 문제가 드러나지 않을 수 있다는 점입니다.
# 
# { 간단한 예제 }
objects = [Dog(), Cat()]
for obj in objects:
    obj.sound() # 멍멍, 야옹

# [ 최종 정리 ]
# 다형성(Polymorphism)이란 동일한 인터페이스나 메서드 호출을 통해 서로 다른 객체를 동일한 방식으로 다룰 수 있으며, 실제 객체에 따라 서로 다른 동작을 수행하는 성질입니다.
# (* 오버라이딩(Overriding)을 포함하여 말한 개념이 다형성(Polymorphism)입니다.)
